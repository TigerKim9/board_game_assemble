import { MODES, PIBAK_MAX, WON_PER_POINT, type Mode } from './logic'

/** 맞고·고스톱 공통 규칙 설명 (meta.rules) */
export function rulesFor(mode: Mode): string[] {
  const c = MODES[mode]
  const intro =
    mode === 'matgo'
      ? `2명이 손패 ${c.hand}장씩, 바닥 ${c.floor}장을 깔고 시작해요. 나머지는 가운데 더미예요.`
      : `3명이 손패 ${c.hand}장씩, 바닥 ${c.floor}장을 깔고 시작해요. 나머지는 가운데 더미예요.`
  return [
    intro,
    '내 차례: 손패 한 장을 내서 바닥의 같은 달 카드와 짝을 맞춰 먹고(없으면 바닥에 내려놓기), 이어서 더미 맨 위 카드를 뒤집어 똑같이 맞춰요.',
    '바닥에 같은 달이 두 장이면 가져올 카드를 골라요. 세 장이면 네 장을 모두 가져와요.',
    '뻑: 낸 카드로 바닥 한 장과 짝을 맞췄는데 뒤집은 카드도 같은 달이면 세 장이 바닥에 남아요. 나중에 그 세 장을 먹으면 "뻑 먹기"로 상대에게서 피 1장씩 뺏어요(내가 싼 뻑을 내가 먹는 자뻑은 2장).',
    '쪽: 바닥에 내려놓은 카드를 뒤집은 카드로 바로 먹으면 상대에게서 피 1장씩.',
    '따닥: 바닥의 같은 달 두 장을 낸 카드와 뒤집은 카드로 모두 먹으면 피 1장씩.',
    '싹쓸이: 내 차례가 끝났을 때 바닥이 텅 비면 피 1장씩 (마지막 차례 제외). 뺏을 때는 일반 피부터, 없으면 쌍피를 가져와요.',
    '흔들기: 바닥에 없는 달을 손에 세 장 쥐고 있으면 그중 한 장을 낼 때 흔들 수 있어요. 이기면 점수 ×2.',
    '폭탄: 손에 같은 달 세 장 + 바닥에 한 장이면 세 장을 한꺼번에 내 네 장을 먹고 피 1장씩 뺏어요. 점수 ×2, 그리고 "빈 차례" 2번(손패 없이 더미만 뒤집기)을 얻어요.',
    '총통: 처음 받은 손패에 같은 달 네 장이 있으면 바로 10점으로 승리!',
    '점수 — 광: 3광 3점(비광 끼면 2점), 4광 4점, 5광 15점. 열끗 5장 1점부터 한 장마다 +1. 고도리(2·4·8월 새) 5점.',
    '점수 — 띠 5장 1점부터 +1. 홍단·청단·초단 각 3점. 피 10장 1점부터 +1 (쌍피는 2장). 9월 국진은 열끗이나 쌍피 중 유리한 쪽으로 자동 계산돼요.',
    `${c.threshold}점 이상이 되면 고 또는 스톱을 골라요. 고를 한 뒤에는 점수가 더 올라야 다시 고/스톱을 할 수 있어요.`,
    '고 보너스: 1고 +1점, 2고 +2점, 3고는 +3점 후 ×2, 4고는 +4점 후 ×4 … (한 번 더 할 때마다 두 배).',
    `배수(각 ×2): 흔들기·폭탄 한 번마다, 피박(내가 피로 점수를 냈는데 상대 피가 1~${PIBAK_MAX}장, 0장은 면제), 광박(광으로 점수를 냈는데 상대 광이 0장), 멍박(열끗 7장 이상으로 점수).`,
    mode === 'matgo'
      ? '고박: 고를 불렀다가 상대가 스톱하면 두 배로 물어요.'
      : '고박(독박): 고를 불렀다가 다른 사람이 스톱하면, 고를 부른 사람이 진 사람 모두의 몫을 혼자 내요.',
    '나가리: 아무도 스톱하지 못한 채 더미가 떨어지면 무승부. 다음 판은 점수가 두 배(연속이면 계속 두 배)예요.',
    `점수는 점당 ${WON_PER_POINT}원의 가상 머니로 정산되어 이름별로 누적돼요. 진짜 돈은 오가지 않으며, 설정 화면에서 초기화할 수 있어요.`,
    '여러 사람이 한 기기로 할 때는 차례마다 화면을 넘겨서 자기 패만 보세요.',
  ]
}
